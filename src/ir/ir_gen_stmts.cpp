// IR generation for the program, functions, declarations and statements.
//
// Control flow becomes labels and jumps:
//
//   if (c) A else B        while (c) A            for (I; c; U) A
//   ---------------        -----------            ---------------
//     t = c                L1:                      I
//     ifFalse t goto L1      t = c                L1:
//     A                      ifFalse t goto L2      t = c
//     goto L2                A                      ifFalse t goto L2
//   L1:                      goto L1                A
//     B                    L2:                      U
//   L2:                                             goto L1
//                                                 L2:

#include "ir_gen.h"

// ------------------------------------------------------------------ helpers

Operand IrGenerator::newTemp(IrType type) { return Operand::temp("t" + std::to_string(++tempCount_), type); }

std::string IrGenerator::newLabel() { return "L" + std::to_string(++labelCount_); }

void IrGenerator::emit(Instr in) {
    if (in.line == 0) in.line = line_;
    fn_->code.push_back(std::move(in));
}

void IrGenerator::emitLabel(const std::string& label) {
    Instr in;
    in.op = Op::LABEL;
    in.label = label;
    emit(in);
}

void IrGenerator::emitJump(Op op, const Operand& cond, const std::string& label) {
    Instr in;
    in.op = op;
    in.a = cond;
    in.label = label;
    emit(in);
}

Operand IrGenerator::varOperand(const Symbol* s) const {
    return Operand::var(s->irName, irTypeOf(s->type), s->global);
}

// The value a variable declared without an initializer starts with.
Operand IrGenerator::defaultValue(IrType type) const {
    switch (type) {
        case IrType::FLOAT: return Operand::floatConst(0.0);
        case IrType::BOOL: return Operand::boolConst(false);
        case IrType::STRING: return Operand::stringConst("");
        default: return Operand::intConst(0);
    }
}

// ----------------------------------------------------------- program, functions

IrProgram IrGenerator::generate(const Program& program) {
    program_ = IrProgram{};

    // Functions first, then the top-level statements as "main".
    for (const StmtPtr& item : program.items) {
        if (item->kind == StmtKind::FUNC_DECL) genFunction(static_cast<const FuncDecl&>(*item));
    }

    program_.main.name = "main";
    fn_ = &program_.main;
    fnSymbol_ = nullptr;
    tempCount_ = labelCount_ = 0;
    for (const StmtPtr& item : program.items) {
        if (item->kind != StmtKind::FUNC_DECL) genStmt(item.get());
    }
    fn_ = nullptr;
    return program_;
}

void IrGenerator::genFunction(const FuncDecl& f) {
    const Symbol* sym = info_.symbolOf(&f);

    program_.functions.emplace_back();
    fn_ = &program_.functions.back();
    fnSymbol_ = sym;
    tempCount_ = labelCount_ = 0;
    line_ = f.line;

    fn_->name = sym->irName;
    fn_->returnType = irTypeOf(sym->type);
    auto params = info_.params.find(&f);
    if (params != info_.params.end()) {
        for (const Symbol* p : params->second) fn_->params.push_back(IrVar{p->irName, irTypeOf(p->type), -1});
    }

    for (const StmtPtr& s : f.body->statements) genStmt(s.get());

    // A void function may simply end; give it an explicit return.
    // (Non-void functions always end in a return: the analysis checked it.)
    if (fn_->returnType == IrType::VOID && (fn_->code.empty() || fn_->code.back().op != Op::RETURN)) {
        Instr ret;
        ret.op = Op::RETURN;
        ret.line = f.line;
        emit(ret);
    }
    fn_ = nullptr;
    fnSymbol_ = nullptr;
}

// ------------------------------------------------------------------ statements

void IrGenerator::genStmt(const Stmt* s) {
    if (!s) return;
    line_ = s->line;
    switch (s->kind) {
        case StmtKind::VAR_DECL: genVarDecl(static_cast<const VarDecl&>(*s)); break;
        case StmtKind::BLOCK:
            for (const StmtPtr& inner : static_cast<const BlockStmt*>(s)->statements) genStmt(inner.get());
            break;
        case StmtKind::IF: genIf(static_cast<const IfStmt&>(*s)); break;
        case StmtKind::WHILE: genWhile(static_cast<const WhileStmt&>(*s)); break;
        case StmtKind::FOR: genFor(static_cast<const ForStmt&>(*s)); break;
        case StmtKind::RETURN: genReturn(static_cast<const ReturnStmt&>(*s)); break;
        case StmtKind::PRINT: genPrint(static_cast<const PrintStmt&>(*s)); break;
        case StmtKind::READ: genRead(static_cast<const ReadStmt&>(*s)); break;
        case StmtKind::EXPR: genExpr(static_cast<const ExprStmt*>(s)->expr.get()); break;
        case StmtKind::FUNC_DECL: break;  // generated by generate()
    }
}

void IrGenerator::genVarDecl(const VarDecl& d) {
    const Symbol* sym = info_.symbolOf(&d);
    Operand v = varOperand(sym);

    IrVar var{sym->irName, v.type, d.arraySize};
    if (sym->global) program_.globals.push_back(var);
    else fn_->locals.push_back(var);

    if (d.arraySize >= 0) {
        Instr in;
        in.op = Op::ARRAY;
        in.dst = v;
        in.count = d.arraySize;
        emit(in);
        return;
    }

    Instr in;
    in.op = Op::COPY;
    in.dst = v;
    in.a = d.init ? genExprAs(d.init.get(), v.type) : defaultValue(v.type);
    emit(in);
}

void IrGenerator::genIf(const IfStmt& s) {
    std::string elseLabel = newLabel();
    Operand cond = genExpr(s.condition.get());
    emitJump(Op::IF_FALSE, cond, elseLabel);
    genStmt(s.thenBranch.get());

    if (!s.elseBranch) {
        emitLabel(elseLabel);
        return;
    }
    std::string endLabel = newLabel();
    emitJump(Op::JUMP, Operand::none(), endLabel);
    emitLabel(elseLabel);
    genStmt(s.elseBranch.get());
    emitLabel(endLabel);
}

void IrGenerator::genWhile(const WhileStmt& s) {
    std::string start = newLabel();
    std::string end = newLabel();
    emitLabel(start);
    line_ = s.line;
    Operand cond = genExpr(s.condition.get());
    emitJump(Op::IF_FALSE, cond, end);
    genStmt(s.body.get());
    emitJump(Op::JUMP, Operand::none(), start);
    emitLabel(end);
}

void IrGenerator::genFor(const ForStmt& s) {
    genStmt(s.init.get());
    std::string start = newLabel();
    std::string end = newLabel();
    emitLabel(start);
    line_ = s.line;
    if (s.condition) {
        Operand cond = genExpr(s.condition.get());
        emitJump(Op::IF_FALSE, cond, end);
    }
    genStmt(s.body.get());
    if (s.update) {
        line_ = s.line;
        genExpr(s.update.get());
    }
    emitJump(Op::JUMP, Operand::none(), start);
    emitLabel(end);
}

void IrGenerator::genReturn(const ReturnStmt& s) {
    Instr in;
    in.op = Op::RETURN;
    if (s.value) in.a = genExprAs(s.value.get(), irTypeOf(fnSymbol_->type));
    emit(in);
}

// print(a, b) prints a, then b, then a newline.
void IrGenerator::genPrint(const PrintStmt& s) {
    for (const ExprPtr& arg : s.args) {
        Instr in;
        in.op = Op::PRINT;
        in.a = genExpr(arg.get());
        emit(in);
    }
    Instr nl;
    nl.op = Op::PRINTLN;
    emit(nl);
}

void IrGenerator::genRead(const ReadStmt& s) {
    const Symbol* sym = info_.symbolOf(s.target.get());
    Operand v = varOperand(sym);

    if (s.target->kind == ExprKind::VARIABLE) {
        Instr in;
        in.op = Op::READ;
        in.dst = v;
        emit(in);
        return;
    }
    // read(a[i]): read into a temporary, then store it in the array.
    auto& target = static_cast<const IndexExpr&>(*s.target);
    Operand index = genExpr(target.index.get());
    Operand value = newTemp(v.type);
    Instr rd;
    rd.op = Op::READ;
    rd.dst = value;
    emit(rd);
    Instr st;
    st.op = Op::STORE;
    st.dst = v;
    st.a = index;
    st.b = value;
    emit(st);
}
